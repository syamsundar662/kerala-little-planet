import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const code=ts.transpileModule(fs.readFileSync('app/render-quality.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext}}).outputText;
const {createRenderQuality}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const quality=createRenderQuality(false);
const ratio=()=>quality.pixelRatio(1920,1080,2);
const original=ratio();
for(let i=0;i<400;i++)quality.sample(33);
assert.ok(ratio()<original,'Sustained slow frames reduce resolution');
const reduced=ratio();
for(let i=0;i<400;i++)quality.sample(1000);
assert.equal(ratio(),reduced,'Tab suspension and loading spikes are ignored');
for(let i=0;i<4000;i++)quality.sample(16.67);
assert.ok(ratio()>reduced,'Sustained healthy frames recover detail');
assert.ok(ratio()<=original,'Recovery stays within the initial budget');
quality.setMode('detail');
const detail=ratio();
for(let i=0;i<1000;i++)quality.sample(40);
assert.equal(ratio(),detail,'Explicit detail setting stays stable');
quality.setMode('smooth');
assert.ok(ratio()<detail);
assert.ok(quality.pixelRatio(3840,2160,3)**2*3840*2160<=1_500_001,'Large screens respect pixel budget');
assert.ok(Number.isFinite(quality.pixelRatio(0,0,2)));
assert.ok(createRenderQuality(true).pixelRatio(390,844,3)<=1.25);
quality.setMode('auto');
for(let i=0;i<30;i++)quality.sample(33);
quality.reset();
assert.equal(quality.sample(33),false,'Resume discards partial sampling window');
console.log('PASS: adaptive downshift/recovery, spike rejection, manual modes, pixel budget, hidden-tab reset.');
